// PostgreSQL schema (Drizzle ORM).
// Run `npm run db:generate` after changing it to create a new SQL migration in /drizzle.
import {
  boolean,
  date,
  doublePrecision,
  index,
  integer,
  jsonb,
  pgEnum,
  pgTable,
  serial,
  text,
  timestamp,
  uniqueIndex,
} from "drizzle-orm/pg-core";

const ts = (name) => timestamp(name, { withTimezone: true, mode: "date" });

export const userRole = pgEnum("user_role", ["student", "parent", "teacher"]);

// Every account: students, parents and teachers.
export const users = pgTable(
  "users",
  {
    id: serial("id").primaryKey(),
    email: text("email").notNull(),
    passwordHash: text("password_hash").notNull(),
    fullName: text("full_name").notNull(),
    role: userRole("role").notNull(),
    gradeSection: text("grade_section"), // teachers: advisory / handled section
    createdAt: ts("created_at").notNull().defaultNow(),
  },
  (t) => [uniqueIndex("users_email_idx").on(t.email)],
);

// Signed-in browsers. The cookie holds a random token; only its SHA-256 hash is stored.
export const sessions = pgTable(
  "sessions",
  {
    id: text("id").primaryKey(),
    userId: integer("user_id")
      .notNull()
      .references(() => users.id, { onDelete: "cascade" }),
    createdAt: ts("created_at").notNull().defaultNow(),
    expiresAt: ts("expires_at").notNull(),
    lastSeenAt: ts("last_seen_at").notNull().defaultNow(),
  },
  (t) => [index("sessions_user_idx").on(t.userId)],
);

// Student records. Each student is linked to at most one parent account.
export const students = pgTable(
  "students",
  {
    id: serial("id").primaryKey(),
    userId: integer("user_id")
      .notNull()
      .references(() => users.id, { onDelete: "cascade" }),
    studentNumber: text("student_number").notNull(),
    fullName: text("full_name").notNull(),
    gradeSection: text("grade_section").notNull(),
    parentUserId: integer("parent_user_id").references(() => users.id, { onDelete: "set null" }),
    parentLinkedAt: ts("parent_linked_at"),
    linkCodeHash: text("link_code_hash"),
    linkCodeExpiresAt: ts("link_code_expires_at"),
    homeLat: doublePrecision("home_lat"),
    homeLng: doublePrecision("home_lng"),
    homeUpdatedAt: ts("home_updated_at"),
    createdAt: ts("created_at").notNull().defaultNow(),
  },
  (t) => [
    uniqueIndex("students_user_idx").on(t.userId),
    uniqueIndex("students_number_idx").on(t.studentNumber),
    uniqueIndex("students_parent_idx").on(t.parentUserId),
  ],
);

// One-time QR code generated by the server for each student, each school day.
// It is used once for the check-in and once for the check-out.
export const dailyPasses = pgTable(
  "daily_passes",
  {
    id: serial("id").primaryKey(),
    studentId: integer("student_id")
      .notNull()
      .references(() => students.id, { onDelete: "cascade" }),
    schoolDate: date("school_date").notNull(),
    token: text("token").notNull(),
    createdAt: ts("created_at").notNull().defaultNow(),
    checkedInAt: ts("checked_in_at"),
    checkedOutAt: ts("checked_out_at"),
  },
  (t) => [
    uniqueIndex("daily_passes_token_idx").on(t.token),
    uniqueIndex("daily_passes_student_date_idx").on(t.studentId, t.schoolDate),
  ],
);

// Class status of a student for one school day.
export const attendance = pgTable(
  "attendance",
  {
    id: serial("id").primaryKey(),
    studentId: integer("student_id")
      .notNull()
      .references(() => students.id, { onDelete: "cascade" }),
    schoolDate: date("school_date").notNull(),
    status: text("status").notNull(), // on_campus | late | checked_out | arrived_home
    late: boolean("late").notNull().default(false),
    checkInAt: ts("check_in_at"),
    checkInVia: text("check_in_via"),
    checkOutAt: ts("check_out_at"),
    checkOutVia: text("check_out_via"),
    arrivedHomeAt: ts("arrived_home_at"),
    updatedAt: ts("updated_at").notNull().defaultNow(),
  },
  (t) => [
    uniqueIndex("attendance_student_date_idx").on(t.studentId, t.schoolDate),
    index("attendance_date_idx").on(t.schoolDate),
  ],
);

// Every scan the server receives, accepted or not (scan accuracy, response time, failures).
export const scanLogs = pgTable(
  "scan_logs",
  {
    id: serial("id").primaryKey(),
    receivedAt: ts("received_at").notNull().defaultNow(),
    source: text("source").notNull(), // device | teacher
    deviceId: text("device_id"),
    studentId: integer("student_id").references(() => students.id, { onDelete: "set null" }),
    action: text("action"), // in | out
    result: text("result").notNull(), // accepted | duplicate | rejected | error
    reason: text("reason"),
    late: boolean("late"),
    httpStatus: integer("http_status"),
    processingMs: integer("processing_ms"),
    deviceRoundTripMs: integer("device_round_trip_ms"),
  },
  (t) => [index("scan_logs_received_idx").on(t.receivedAt)],
);

// In-app notifications for parents, with the times needed for the response-time analysis.
export const notifications = pgTable(
  "notifications",
  {
    id: serial("id").primaryKey(),
    parentUserId: integer("parent_user_id")
      .notNull()
      .references(() => users.id, { onDelete: "cascade" }),
    studentId: integer("student_id")
      .notNull()
      .references(() => students.id, { onDelete: "cascade" }),
    type: text("type").notNull(), // check_in | late | check_out | eta | arrived_home | trip_stopped | sos
    title: text("title").notNull(),
    body: text("body").notNull().default(""),
    mapsUrl: text("maps_url"),
    eventAt: ts("event_at").notNull(), // when the scan / GPS event happened
    createdAt: ts("created_at").notNull().defaultNow(),
    pushStatus: text("push_status"), // sent | partial | failed | no_subscription | disabled
    pushSentAt: ts("push_sent_at"),
    deliveredAt: ts("delivered_at"), // first time the parent's phone received it
    deliveredVia: text("delivered_via"), // push | in_app
    readAt: ts("read_at"),
  },
  (t) => [index("notifications_parent_idx").on(t.parentUserId, t.createdAt)],
);

// Browser push subscriptions (phone notifications even when the app is closed).
export const pushSubscriptions = pgTable(
  "push_subscriptions",
  {
    id: serial("id").primaryKey(),
    userId: integer("user_id")
      .notNull()
      .references(() => users.id, { onDelete: "cascade" }),
    endpoint: text("endpoint").notNull(),
    p256dh: text("p256dh").notNull(),
    auth: text("auth").notNull(),
    userAgent: text("user_agent"),
    createdAt: ts("created_at").notNull().defaultNow(),
    lastSuccessAt: ts("last_success_at"),
    failureCount: integer("failure_count").notNull().default(0),
  },
  (t) => [uniqueIndex("push_endpoint_idx").on(t.endpoint), index("push_user_idx").on(t.userId)],
);

// A trip home after check-out, tracked with the phone's GPS until arrival.
export const trips = pgTable(
  "trips",
  {
    id: serial("id").primaryKey(),
    studentId: integer("student_id")
      .notNull()
      .references(() => students.id, { onDelete: "cascade" }),
    schoolDate: date("school_date").notNull(),
    status: text("status").notNull(), // active | arrived | stopped
    startedAt: ts("started_at").notNull().defaultNow(),
    startLat: doublePrecision("start_lat").notNull(),
    startLng: doublePrecision("start_lng").notNull(),
    initialRemainingKm: doublePrecision("initial_remaining_km").notNull(),
    initialEtaMinutes: integer("initial_eta_minutes").notNull(),
    predictedArrivalAt: ts("predicted_arrival_at").notNull(), // first ETA, used for the ETA error
    lastLat: doublePrecision("last_lat"),
    lastLng: doublePrecision("last_lng"),
    lastAccuracyM: doublePrecision("last_accuracy_m"),
    lastFixAt: ts("last_fix_at"),
    remainingKm: doublePrecision("remaining_km"),
    etaMinutes: integer("eta_minutes"),
    etaAt: ts("eta_at"),
    speedKmh: doublePrecision("speed_kmh"),
    arrivedAt: ts("arrived_at"),
    endedAt: ts("ended_at"),
    etaErrorMinutes: doublePrecision("eta_error_minutes"), // actual minus first predicted arrival
  },
  (t) => [index("trips_student_idx").on(t.studentId, t.startedAt)],
);

export const locationPings = pgTable(
  "location_pings",
  {
    id: serial("id").primaryKey(),
    tripId: integer("trip_id")
      .notNull()
      .references(() => trips.id, { onDelete: "cascade" }),
    lat: doublePrecision("lat").notNull(),
    lng: doublePrecision("lng").notNull(),
    accuracyM: doublePrecision("accuracy_m"),
    remainingKm: doublePrecision("remaining_km"),
    etaMinutes: integer("eta_minutes"),
    recordedAt: ts("recorded_at").notNull().defaultNow(),
  },
  (t) => [index("location_pings_trip_idx").on(t.tripId, t.recordedAt)],
);

export const sosAlerts = pgTable(
  "sos_alerts",
  {
    id: serial("id").primaryKey(),
    studentId: integer("student_id")
      .notNull()
      .references(() => students.id, { onDelete: "cascade" }),
    createdAt: ts("created_at").notNull().defaultNow(),
    lat: doublePrecision("lat"),
    lng: doublePrecision("lng"),
    accuracyM: doublePrecision("accuracy_m"),
    locationSource: text("location_source").notNull(), // live | last_known | none
    status: text("status").notNull().default("open"), // open | resolved
    resolvedAt: ts("resolved_at"),
  },
  (t) => [index("sos_student_idx").on(t.studentId, t.createdAt)],
);

export const appSettings = pgTable("app_settings", {
  key: text("key").primaryKey(),
  value: text("value").notNull(),
  updatedAt: ts("updated_at").notNull().defaultNow(),
  updatedBy: integer("updated_by").references(() => users.id, { onDelete: "set null" }),
});

// Latest status of each ESP32-CAM scanner (from its heartbeats).
export const devices = pgTable("devices", {
  id: text("id").primaryKey(),
  firmware: text("firmware"),
  lastSeenAt: ts("last_seen_at"),
  lastBootAt: ts("last_boot_at"),
  lastResetReason: text("last_reset_reason"),
  rssi: integer("rssi"),
  uptimeS: integer("uptime_s"),
  freeHeap: integer("free_heap"),
  freePsram: integer("free_psram"),
  scans: integer("scans"),
  accepted: integer("accepted"),
  rejected: integer("rejected"),
  decodeFails: integer("decode_fails"),
  httpErrors: integer("http_errors"),
  wifiReconnects: integer("wifi_reconnects"),
});

// Newest camera picture from each scanner, for the teacher-only camera view. The scanner sends
// pictures only during its preview window after a restart, and each one replaces the last.
export const cameraFrames = pgTable("camera_frames", {
  deviceId: text("device_id").primaryKey(),
  jpegBase64: text("jpeg_base64").notNull(),
  width: integer("width").notNull(),
  height: integer("height").notNull(),
  seq: integer("seq").notNull(),
  stats: jsonb("stats"),
  receivedAt: ts("received_at").notNull().defaultNow(),
});

// Boots and failures reported by the scanners (for MTBF).
export const deviceEvents = pgTable(
  "device_events",
  {
    id: serial("id").primaryKey(),
    deviceId: text("device_id").notNull(),
    type: text("type").notNull(), // boot | crash | wifi_drop | http_error
    detail: jsonb("detail"),
    at: ts("at").notNull().defaultNow(),
  },
  (t) => [index("device_events_idx").on(t.deviceId, t.at)],
);
